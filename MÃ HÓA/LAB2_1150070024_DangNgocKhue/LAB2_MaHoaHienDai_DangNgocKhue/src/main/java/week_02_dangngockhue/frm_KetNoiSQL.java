    private void btn_testActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_testActionPerformed
        try {
            int port = Integer.parseInt(txt_port.getText().trim());

            DbConfig.set(
                    txt_server.getText().trim(),
                    port,
                    txt_database.getText().trim(),
                    txt_user.getText().trim(),
                    txt_password.getPassword()
            );

            lbl_status.setText(
                    "<html>" + DbConfig.test() + "</html>"
            );

        } catch (Exception ex) {
            DbConfig.clear();

            lbl_status.setText(
                    "<html>Kết nối thất bại: "
                    + ex.getMessage() + "</html>"
            );

            JOptionPane.showMessageDialog(
                    this,
                    ex.getMessage(),
                    "Không kết nối được SQL Server",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btn_testActionPerformed

